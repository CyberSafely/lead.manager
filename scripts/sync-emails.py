#!/usr/bin/env python3
"""Sync the email notes in this project's emails/<category>/*.md into the Lead Manager.

emails/ is the source of truth (the vault's Emails/ folder is a shortcut to it). Each subfolder is a category
in the app; each note with a template_id is one email. Writes email-templates.js to:
  public/        what `npm run dev` serves and the builds copy
  dist/, dist-cloud/  the built apps, if they exist, so a reload picks up the change without rebuilding
  the vault's Lead Outreach/  the legacy Outreach Manager.html (set CS_VAULT if the vault moves)

    npm run sync-emails          once
    npm run emails:watch         keep running: re-syncs whenever a note changes, then just reload the app
`npm run dev` / `dev:cloud` re-sync on their own when a note changes (vite.config.ts).
"""
import hashlib, json, os, re, sys, time
from datetime import datetime
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
SRC = PROJECT / "emails"
VAULT = Path(os.environ.get("CS_VAULT", "/home/giancarlo/Desktop/CyberSafely"))
OUTS = [PROJECT / "public" / "email-templates.js", PROJECT / "dist" / "email-templates.js",
        PROJECT / "dist-cloud" / "email-templates.js", VAULT / "Lead Outreach" / "email-templates.js"]
STAGES = {"contacted": "contacted", "engaged": "engaged", "declined": "lost", "live": "live", "active": "active", "nurture": "nurture"}


def frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    fm = {}
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            if v:
                fm[k.strip()] = v.strip().strip('"')
    return fm


def block(text, *headings):
    """First ```text block under one of the given ## headings (before the next ## heading)."""
    for h in headings:
        m = re.search(rf"^## {h}\s*$(.*?)(?=^## |\Z)", text, re.S | re.M)
        if m:
            b = re.search(r"```text\n(.*?)\n```", m.group(1), re.S)
            if b:
                return b.group(1)
    return ""


def category(folder):
    return re.sub(r"^(\d+) ", r"\1 · ", folder)


def same_version(path, version):
    """True when the file already holds this content (only the "generated" time would change)."""
    try:
        return f'"version": "{version}"' in path.read_text()
    except OSError:
        return False


def sync(force=False):
    """Rebuild email-templates.js from emails/. Returns True if anything changed."""
    templates, cats = [], []
    for folder in sorted(p for p in SRC.iterdir() if p.is_dir()):
        for f in sorted(folder.glob("*.md")):
            text = f.read_text()
            fm = frontmatter(text)
            tid = fm.get("template_id")
            if not tid:
                continue
            h1 = re.search(r"^# (.+)$", text, re.M)
            stage = STAGES.get(fm.get("stage_after_send", "").lower())
            t = {"id": tid, "phase": category(folder.name), "name": h1.group(1).strip() if h1 else f.stem,
                 "to": stage, "subject": block(text, "Subject"), "body": block(text, "Body", "Script"),
                 "kind": fm.get("kind", "Email"), "file": f"{folder.name}/{f.name}"}
            if fm.get("touch", "").isdigit():
                t["seq"] = int(fm["touch"])
            if fm.get("path"):
                t["path"] = fm["path"]
            if fm.get("marks_shared", "").lower() == "true":
                t["shared"] = True
            if not t["body"]:
                print(f"! no Body/Script text block, skipped: {t['file']}")
                continue
            templates.append(t)
            if t["phase"] not in cats:
                cats.append(t["phase"])

    ids = [t["id"] for t in templates]
    dups = {i for i in ids if ids.count(i) > 1}
    if dups:
        raise ValueError(f"Duplicate template_id in emails/: {', '.join(sorted(dups))}")

    # Every note in emails/ (templates, scripts and guides like Email Flow.md), in full, for the Emails explorer
    files = []
    for f in sorted(SRC.rglob("*.md")):
        text = f.read_text()
        fm = frontmatter(text)
        rel = f.relative_to(SRC)
        h1 = re.search(r"^# (.+)$", text, re.M)
        files.append({"path": str(rel), "folder": category(rel.parts[0]) if len(rel.parts) > 1 else "",
                      "name": h1.group(1).strip() if h1 else f.stem, "id": fm.get("template_id"), "fm": fm,
                      "md": re.sub(r"^---\n.*?\n---\n", "", text, count=1, flags=re.S)})
    payload = {"templates": templates, "categories": cats, "files": files}
    payload["version"] = hashlib.sha1(json.dumps(payload, sort_keys=True).encode()).hexdigest()[:12]
    payload["generated"] = datetime.now().isoformat(timespec="seconds")
    js = ("// Generated by scripts/sync-emails.py from the project's emails/ folder. Don't edit by hand.\n"
          f"window.VAULT_TEMPLATES = {json.dumps(payload, ensure_ascii=False, indent=1)};\n")
    if not force and same_version(OUTS[0], payload["version"]):
        return False
    for out in OUTS:
        if out.parent.exists():
            out.write_text(js)
    print(f"{len(templates)} templates in {len(cats)} categories (version {payload['version']}) → " +
          ", ".join(str(o.relative_to(PROJECT)) if o.is_relative_to(PROJECT) else "vault legacy app" for o in OUTS if o.parent.exists()))
    for c in cats:
        print(f"  {c}: " + ", ".join(t["id"] for t in templates if t["phase"] == c))
    return True


def snapshot():
    return sorted((str(f), f.stat().st_mtime_ns, f.stat().st_size) for f in SRC.rglob("*.md"))


if __name__ == "__main__":
    if "--watch" not in sys.argv:
        sync(force=True)
        sys.exit(0)
    print(f"Watching {SRC.relative_to(PROJECT)}/ … save a note, then reload the app. Ctrl+C to stop.")
    last = None
    while True:
        snap = snapshot()
        if snap != last:
            try:
                if sync() and last is not None:
                    print(f"  synced at {datetime.now():%H:%M:%S}")
            except ValueError as e:
                print(f"! {e}")
            last = snap
        time.sleep(1)
